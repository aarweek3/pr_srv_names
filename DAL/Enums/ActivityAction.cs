using System.ComponentModel.DataAnnotations;

namespace DAL.Enums;

/// <summary>
/// Типы действий пользователя для логирования
/// Включает стандартные действия и OAuth-аутентификацию
/// </summary>
public enum ActivityAction
{
    // ==========================================
    // АУТЕНТИФИКАЦИЯ
    // ==========================================

    /// <summary>
    /// Вход в систему
    /// </summary>
    [Display(Name = "Вход в систему")] Login,

    /// <summary>
    /// Выход из системы
    /// </summary>
    [Display(Name = "Выход из системы")] Logout,

    /// <summary>
    /// Регистрация нового пользователя
    /// </summary>
    [Display(Name = "Регистрация")] Register,

    // ==========================================
    // УПРАВЛЕНИЕ ПАРОЛЕМ
    // ==========================================

    /// <summary>
    /// Запрос на восстановление пароля
    /// </summary>
    [Display(Name = "Запрос восстановления пароля")]
    ForgotPassword,

    /// <summary>
    /// Сброс пароля
    /// </summary>
    [Display(Name = "Сброс пароля")] ResetPassword,

    /// <summary>
    /// Изменение пароля
    /// </summary>
    [Display(Name = "Изменение пароля")] ChangePassword,

    // ==========================================
    // ПРОФИЛЬ ПОЛЬЗОВАТЕЛЯ
    // ==========================================

    /// <summary>
    /// Обновление профиля
    /// </summary>
    [Display(Name = "Обновление профиля")] UpdateProfile,

    // ==========================================
    // УПРАВЛЕНИЕ ПОЛЬЗОВАТЕЛЯМИ (АДМИН)
    // ==========================================

    /// <summary>
    /// Создание пользователя
    /// </summary>
    [Display(Name = "Создание пользователя")]
    CreateUser,

    /// <summary>
    /// Обновление пользователя
    /// </summary>
    [Display(Name = "Обновление пользователя")]
    UpdateUser,

    /// <summary>
    /// Блокировка пользователя
    /// </summary>
    [Display(Name = "Блокировка пользователя")]
    BlockUser,

    /// <summary>
    /// Разблокировка пользователя
    /// </summary>
    [Display(Name = "Разблокировка пользователя")]
    UnblockUser,

    /// <summary>
    /// Удаление пользователя
    /// </summary>
    [Display(Name = "Удаление пользователя")]
    DeleteUser,

    // ==========================================
    // НАСТРОЙКИ И ЛОГИ
    // ==========================================

    /// <summary>
    /// Обновление настроек
    /// </summary>
    [Display(Name = "Обновление настроек")]
    UpdateSettings,

    /// <summary>
    /// Просмотр логов
    /// </summary>
    [Display(Name = "Просмотр логов")] ViewLogs,

    // ==========================================
    // ВНЕШНЯЯ АУТЕНТИФИКАЦИЯ (OAuth)
    // ==========================================

    /// <summary>
    /// Вход через внешний сервис (Google, Facebook и т.д.)
    /// </summary>
    [Display(Name = "Вход через внешний сервис")]
    ExternalLogin,

    /// <summary>
    /// Привязка внешнего аккаунта
    /// </summary>
    [Display(Name = "Привязка внешнего аккаунта")]
    LinkExternalAccount,

    /// <summary>
    /// Отвязка внешнего аккаунта
    /// </summary>
    [Display(Name = "Отвязка внешнего аккаунта")]
    UnlinkExternalAccount,

    /// <summary>
    /// Регистрация через внешний сервис
    /// </summary>
    [Display(Name = "Регистрация через внешний сервис")]
    ExternalRegister
}